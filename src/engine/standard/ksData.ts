export type KsClass = 'WIDE' | 'MIDDLE' | 'NARROW';
export interface KsEntry extends StdEntry { cls: KsClass; nH: number; nB: number; }

/** 공칭치수로 계열 분류 (H사 규칙과 동일) */
function classify(nH: number, nB: number): KsClass {
  if (nB === nH) return 'WIDE';
  if (nB >= 250 || nH <= 1.6 * nB) return 'MIDDLE';
  return 'NARROW';
}
/** S규칙 볼트직경 — 공칭폭 기준 */
function diaFor(nB: number): number {
  return nB <= 125 ? 16 : nB <= 250 ? 20 : 24;
}

const build = (r: Row): KsEntry => {
  const [nH, nB, H, B, tw, tf] = r;
  const name = `H-${H}x${B}x${tw}x${tf}`;
  return { name, dia: diaFor(nB), cls: classify(nH, nB), nH, nB };
};
const ENTRIES = RAW.map(build);
// 시리즈(공칭춤) 오름차순 · 동일 공칭 내 실춤 오름차순
const bySize = (a: KsEntry, b: KsEntry) => a.nH - b.nH || a.nB - b.nB || parseInt(a.name.split('x')[0].slice(2)) - parseInt(b.name.split('x')[0].slice(2));

/** 기둥(COLUMN) = WIDE 계열 */
export const KS_COLUMN: KsEntry[] = ENTRIES.filter(e => e.cls === 'WIDE').sort(bySize);
/** 보(GIRDER) = MIDDLE 계열 후 NARROW 계열 */
export const KS_BEAM: KsEntry[] = [
  ...ENTRIES.filter(e => e.cls === 'MIDDLE').sort(bySize),
  ...ENTRIES.filter(e => e.cls === 'NARROW').sort(bySize),
];
/** 전 단면(보·기둥 공통) — WIDE→MIDDLE→NARROW 순, 각 계열 오름차순. K 모드 부재리스트. */
export const KS_FULL: KsEntry[] = [...KS_COLUMN, ...KS_BEAM];
/** 전체(참조용) */
export const KS_ALL: KsEntry[] = ENTRIES;

/** 단면명 → 계열(WIDE/MIDDLE/NARROW) 조회 (결과표 계열 구분밴드용) */
const CLS_MAP = new Map<string, KsClass>(ENTRIES.map(e => [e.name, e.cls]));
export const ksClassOf = (name: string): KsClass | undefined => CLS_MAP.get(name);
/** 계열 밴드 표기 라벨 */
export const ksClassLabel = (c: KsClass): string =>
  c === 'WIDE' ? 'WIDE FLANGE (광폭)' : c === 'MIDDLE' ? 'MIDDLE FLANGE (중폭)' : 'NARROW FLANGE (세폭)';
